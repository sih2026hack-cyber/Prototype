assert.deepEqual(r.signs[0].box, [100, 200, 300, 400]);

r = await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 0.4, summary: 'Maybe.', signs: [] }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'cant_tell', 'a weak guess is reported as "can\'t tell"');

r = await createLens({ ask: answer({ verdict: 'no_ai_signs', confidence: 0.8, summary: 'A studio photo of fruit.', signs: [{ what: 'skin', why: 'Natural pores.', box: [1, 1, 50, 50] }] }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'no_ai_signs'); assert.equal(r.label, 'No signs of AI found');
assert.match(r.summary, /^A studio photo of fruit\. That doesn't prove it's real/);
assert.equal(r.signs.length, 0, 'no "looks real" evidence is ever listed');
r = await createLens({ ask: answer({ verdict: 'likely_authentic', confidence: 0.95, signs: [] }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'no_ai_signs', 'an "authentic" answer is never passed on as proof');

// The second look runs only when the first found nothing; only a confident answer with evidence counts.
const clean = answer({ verdict: 'no_ai_signs', confidence: 0.8, summary: 'Friends on a beach.', signs: [] });
r = await createLens({ ask: clean, lookAgain: answer({ verdict: 'likely_ai', confidence: 0.82, summary: 'Four friends on a beach; one arm belongs to nobody.', signs: [{ what: 'arm on the right', why: 'The arm belongs to nobody.', box: [900, 500, 1000, 800] }] }), segment: noSam }).assess(photo);
assert.equal(r.verdict, 'likely_ai'); assert.equal(r.signs[0].what, 'arm on the right'); assert.equal(r.summary, 'Four friends on a beach; one arm belongs to nobody.', 'the first summary ("nothing found") is replaced');
for (const again of [answer({ verdict: 'likely_ai', confidence: 0.5, signs: [sign] }), answer({ verdict: 'likely_ai', confidence: 0.9, signs: [] }), async () => { throw new Error('timeout'); }]) {
  assert.equal((await createLens({ ask: clean, lookAgain: again, segment: noSam }).assess(photo)).verdict, 'no_ai_signs');
}
r = await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 0.9, signs: [sign] }), lookAgain: answer({ verdict: 'likely_ai', confidence: 0.95, signs: [{ what: 'other', why: 'Other.', box: [1, 1, 9, 9] }] }), segment: noSam }).assess(photo);
assert.equal(r.signs[0].what, 'left hand', 'when the first look found signs, its evidence is kept');
let looked = false;
await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 0.9, signs: [sign] }), lookAgain: async () => { looked = true; return '{}'; }, segment: noSam }).assess(jpeg(800, 800, [[0xe1, bytes('xmp trainedAlgorithmicMedia')]]));
assert.equal(looked, false, 'no second look when the file is labelled as AI');

// Filters and edits are reported apart from the verdict; unknown types and empty ones are dropped.
