// --- Meta's SAM parser reads SAM 3.1 output (sample line from the Meta docs) ---
const line = "<0f>0<|box;x1=211;y1=228;x2=270;y2=254;w=320;h=334|><|mask;x=0;y=0;data=27,60,~!!!!M!0c[0o91w?q1!pIH4pPRVp2B3'7`e.ioeAf6-k/#Xd8%dX9x(|>";
async function* events() {
  yield { type: 'response.output_text.delta', delta: line, output_index: 0, content_index: 0, item_id: 'm' };
  yield { type: 'response.output_text.done', text: line, output_index: 0, content_index: 0, item_id: 'm' };
  yield { type: 'response.completed', response: { status: 'completed' } };
}
const seg = await parseImageStream(events()).finalResult;
const [mask] = recordsOfKind(seg.records, 'mask');
assert.equal(mask.mask.width, 60); assert.equal(mask.mask.height, 27);
assert.match(decodeMaskToSVGPath(mask.mask), /^M/);

