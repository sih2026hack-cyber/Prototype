// --- tiny hand-built image files ---
const be32 = n => [(n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255];
const bytes = s => [...Buffer.from(s, 'latin1')];
function png(width, height, extraChunks = []) {
  const chunk = (type, body) => [...be32(body.length), ...bytes(type), ...body, 0, 0, 0, 0];
  return new Uint8Array([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
    ...chunk('IHDR', [...be32(width), ...be32(height), 8, 6, 0, 0, 0]),
    ...extraChunks.flatMap(([t, b]) => chunk(t, b)),
    ...chunk('IDAT', bytes('Midjourney trainedAlgorithmicMedia')), // pixel data must never count as a label
    ...chunk('IEND', []),
  ]);
}
function jpeg(width, height, app = []) {
  const seg = (marker, body) => [0xff, marker, ((body.length + 2) >> 8) & 255, (body.length + 2) & 255, ...body];
  return new Uint8Array([
    0xff, 0xd8,
    ...app.flatMap(([m, b]) => seg(m, b)),
    ...seg(0xc0, [8, (height >> 8) & 255, height & 255, (width >> 8) & 255, width & 255, 1, 1, 0x11, 0]),
    0xff, 0xda, 0, 2, ...bytes('Stable Diffusion'), 0xff, 0xd9, // scan data: never read
  ]);
}

