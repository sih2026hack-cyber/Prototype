// --- the lens: code combines the file's facts with the model's careful opinion ---
const answer = obj => async () => JSON.stringify(obj);
const noSam = async () => [];
const photo = jpeg(1000, 500);
const sign = { what: 'left hand', why: 'The hand has six fingers.', box: [100, 200, 300, 400] };

let r = await createLens({ ask: answer({ verdict: 'likely_ai', confidence: 0.85, kind: 'photo', summary: 'Several signs of AI.', signs: [sign], harm: { harmful: false, category: 'none', reason: '' } }), segment: noSam }).assess(photo);
